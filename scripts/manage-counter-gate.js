#!/usr/bin/env node
'use strict';

const crypto = require('node:crypto');
const path = require('node:path');
const gate = require('../counter-gate.js');
const {
  EVIDENCE_ARGUMENT_FIELDS, authorEvidenceReport, captureEvidenceIdentity,
  validateEvidenceIdentityOptions
} = require('../release-evidence-identity.js');
const { reserveReport } = require('./migrate-legacy-ownership.js');

function parseArgs(argv) {
  const result = {
    action: '', projectId: '', targetMode: 'production', confirmProject: '',
    adminUid: '', gateId: '', gateGeneration: '', output: '',
    windowId: '', controlId: ''
  };
  const fields = {
    '--action': 'action', '--project': 'projectId', '--target-mode': 'targetMode',
    '--confirm-project': 'confirmProject', '--admin-uid': 'adminUid',
    '--gate-id': 'gateId', '--gate-generation': 'gateGeneration', '--output': 'output',
    ...EVIDENCE_ARGUMENT_FIELDS
  };
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    const field = fields[argument];
    if (!field) throw new Error('Unknown argument: ' + argument);
    const value = argv[++index];
    if (!value || value.startsWith('--')) throw new Error(argument + ' requires a value.');
    result[field] = value;
  }
  if (!['lock', 'status', 'unlock'].includes(result.action)) {
    throw new Error('--action must be lock, status, or unlock.');
  }
  if (!result.projectId) throw new Error('--project is required.');
  if (!['production', 'emulator'].includes(result.targetMode)) {
    throw new Error('--target-mode must be production or emulator.');
  }
  if (result.action !== 'status') {
    if (result.confirmProject !== result.projectId) {
      throw new Error('Mutating operations require an exact --confirm-project.');
    }
    if (!result.adminUid) throw new Error('Mutating operations require --admin-uid.');
  }
  if (result.action === 'lock' && result.gateId) {
    throw new Error('Lock identities are generated by the CLI; do not pass --gate-id.');
  }
  if (result.action === 'unlock' && (!result.gateId || !result.gateGeneration)) {
    throw new Error('Unlock requires --gate-id and --gate-generation.');
  }
  validateEvidenceIdentityOptions(result);
  return result;
}

function validateTarget(options, environment = process.env) {
  const firestoreHost = environment.FIRESTORE_EMULATOR_HOST || '';
  const authHost = environment.FIREBASE_AUTH_EMULATOR_HOST || '';
  if (options.targetMode === 'emulator') {
    if (!/^demo-/.test(options.projectId)) {
      throw new Error('Emulator mode requires a demo-* project.');
    }
    if (firestoreHost !== '127.0.0.1:8080' || authHost !== '127.0.0.1:9099') {
      throw new Error('Emulator mode requires FIRESTORE_EMULATOR_HOST=127.0.0.1:8080 and FIREBASE_AUTH_EMULATOR_HOST=127.0.0.1:9099.');
    }
    return { targetMode: 'emulator', firestoreHost, authHost };
  }
  if (firestoreHost || authHost) {
    throw new Error('Production mode refuses stale Firestore/Auth emulator environment variables.');
  }
  return { targetMode: 'production', firestoreHost: '', authHost: '' };
}

function productionDependencies() {
  return {
    reserveReport,
    now: () => new Date().toISOString(),
    createLockId: () => crypto.randomUUID(),
    async initialize(projectId) {
      const admin = require('firebase-admin');
      const app = admin.initializeApp({ projectId });
      return {
        db: admin.firestore(app),
        serverTimestamp: () => admin.firestore.FieldValue.serverTimestamp(),
        close() { return app.delete(); }
      };
    },
    runCounterGateOperation: gate.runCounterGateOperation,
    writeLine(line) { process.stdout.write(line + '\n'); }
  };
}

function failureReport(base, error) {
  return {
    ...base,
    status: 'failed',
    safeToRunCounterMigration: false,
    error: String(error && error.message || error)
  };
}

async function main(argv = process.argv.slice(2), dependencies = productionDependencies()) {
  const options = parseArgs(argv);
  const target = validateTarget(options, dependencies.environment || process.env);
  const identity = captureEvidenceIdentity(
    { ...options, targetMode: target.targetMode },
    { tool: 'counter-gate-cli', schemaVersion: 2 },
    dependencies.now
  );
  const generatedGateId = options.action === 'lock'
    ? String(options.gateId || dependencies.createLockId())
    : options.gateId;
  const output = options.output || path.resolve(
    'counter-gate-' + options.action + '-' + options.projectId + '-' + Date.now() + '.json'
  );
  const base = authorEvidenceReport({
    action: options.action,
    lockId: generatedGateId || '',
    requestedGeneration: options.gateGeneration || '',
    status: 'reserved-fail-closed',
    safeToRunCounterMigration: false
  }, identity);
  const reservation = dependencies.reserveReport(
    output, JSON.stringify(base, null, 2) + '\n'
  );
  let services;
  try {
    services = await dependencies.initialize(options.projectId);
    const operation = await dependencies.runCounterGateOperation({
      db: services.db,
      action: options.action,
      projectId: options.projectId,
      targetMode: target.targetMode,
      actorUid: options.adminUid,
      gateId: generatedGateId,
      gateGeneration: options.gateGeneration,
      createLockId: dependencies.createLockId,
      serverTimestamp: services.serverTimestamp
    });
    const report = authorEvidenceReport({
      ...base,
      ...operation,
      targetMode: target.targetMode,
      status: 'complete',
      safeToRunCounterMigration: options.action === 'lock' && operation.gate &&
        operation.gate.locked === true
    }, identity);
    await reservation.commit(JSON.stringify(report, null, 2) + '\n');
    try { dependencies.writeLine(JSON.stringify(report, null, 2)); } catch (_) {
      // The durable committed report is authoritative.
    }
    return report;
  } catch (error) {
    const report = authorEvidenceReport(failureReport(base, error), identity);
    try {
      await reservation.commit(JSON.stringify(report, null, 2) + '\n');
    } catch (publicationError) {
      throw new Error(
        String(error && error.message || error) + '; fail-closed report remains at ' +
        (reservation.failClosedPath || output + '.reserved') + '; publication error: ' +
        String(publicationError && publicationError.message || publicationError),
        { cause: error }
      );
    }
    throw error;
  } finally {
    if (services && typeof services.close === 'function') await services.close();
  }
}

if (require.main === module) main().catch(error => {
  process.stderr.write('Counter gate operation failed: ' +
    String(error && error.message || error) + '\n');
  process.exitCode = 1;
});

module.exports = {
  main,
  parseArgs,
  productionDependencies,
  reserveReport,
  validateTarget
};
